export type DictKey = keyof (typeof dict)["th"];

export async function getLocale(): Promise<Locale> {
  try {
    const c = await cookies();
    const v = c.get("locale")?.value;
    return v === "en" ? "en" : "th";
  } catch {
    return "th";
  }
}

export async function getT() {
  const locale = await getLocale();
  return {
    locale,
    t: (key: DictKey): string => dict[locale][key] ?? dict.th[key] ?? key,
  };
}

export function tFor(locale: Locale) {
  return (key: DictKey): string => dict[locale][key] ?? dict.th[key] ?? key;
}
